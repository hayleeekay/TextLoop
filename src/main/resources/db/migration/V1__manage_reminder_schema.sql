create table if not exists reminders (
    id bigint generated by default as identity primary key,
    message varchar(1000) not null,
    phone_number varchar(255) not null,
    scheduled_at timestamp(6) not null,
    status varchar(255) not null check (status in ('PENDING', 'SENT')),
    current_delivery_id uuid,
    withdrawn_at timestamp(6),
    version bigint not null default 0,
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null
);

-- Older local databases predate the wider message and delivery tracking.
alter table reminders
    alter column message type varchar(1000),
    add column if not exists current_delivery_id uuid,
    add column if not exists withdrawn_at timestamp(6),
    add column if not exists version bigint not null default 0;

create table if not exists deliveries (
    id uuid primary key,
    reminder_id bigint not null references reminders (id) on delete cascade,
    phone_number varchar(255) not null,
    message text not null,
    snooze_minutes integer,
    snooze_footer varchar(160),
    submission_order bigint,
    snoozed_reminder_id bigint,
    snooze_hint_sent boolean,
    state varchar(255) not null check (state in (
        'READY', 'UNKNOWN', 'ACCEPTED', 'RETRYABLE_REJECTION', 'PERMANENT_REJECTION'
    )),
    reason varchar(255) not null check (reason in (
        'NOT_SUBMITTED', 'SUBMISSION_UNCONFIRMED', 'ACCEPTANCE_CONFIRMED',
        'RETRYABLE_NON_ACCEPTANCE', 'PERMANENT_NON_ACCEPTANCE', 'LEGACY_UNRECORDED'
    )),
    attempt_count integer not null,
    next_attempt_at timestamp(6),
    extra_attempt_permitted boolean not null,
    stopped_by_number_change boolean not null default false,
    acceptance_reference varchar(255),
    replaces_delivery_id uuid,
    recovery_action varchar(255) check (recovery_action in (
        'FINALIZE', 'CONFIRM_ACCEPTED', 'CONFIRM_RETRYABLE_REJECTION',
        'CONFIRM_PERMANENT_REJECTION', 'RETRY_ONCE', 'REPLACE_UNKNOWN'
    )),
    recovered_at timestamp(6),
    created_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    version bigint not null
);

alter table deliveries
    add column if not exists stopped_by_number_change boolean not null default false,
    add column if not exists snooze_minutes integer,
    add column if not exists snooze_footer varchar(160),
    add column if not exists submission_order bigint,
    add column if not exists snoozed_reminder_id bigint,
    add column if not exists snooze_hint_sent boolean;

create table if not exists reminder_reuses (
    id bigint generated by default as identity primary key,
    source_reminder_id bigint not null references reminders (id) on delete cascade,
    operation_id uuid not null,
    expected_version bigint not null,
    scheduled_at timestamp(6) not null,
    requested_message varchar(1000),
    result_reminder_id bigint not null references reminders (id) on delete cascade,
    constraint reminder_reuse_operation unique (source_reminder_id, operation_id)
);

alter table reminder_reuses add column if not exists requested_message varchar(1000);

create table if not exists reminder_number (
    id integer primary key,
    phone_number varchar(16) not null
);

create table if not exists snooze_settings (
    id integer primary key,
    minutes integer not null
);

create table if not exists snooze_replies (
    id uuid primary key,
    phone_number varchar(16),
    reply_text varchar(255),
    scheduled_at timestamp(6)
);
